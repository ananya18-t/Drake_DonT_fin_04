"""
gateway.py

Master FastAPI gateway for the Financial Crime & Insider Risk Intelligence Platform.
Orchestrates Neo4j (graph patterns), the ML Anomaly Engine (:8001) and the local Qwen
model on llama-server (:8080), and serves the React dashboard under ``/api/v1``
(contract: ``frontend-dashboard/src/api/client.js``).

LLM narratives are slow relative to a UI request, so they are generated by a single
background worker (llama-server has one slot) in priority order: the alert a reviewer
opens jumps the queue; CRITICAL/HIGH alerts are pre-generated after the alert book builds.
"""

